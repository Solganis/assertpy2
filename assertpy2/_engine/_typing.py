    # what a number may be compared against: anything that can produce a float. Named as a capability
    # rather than as a list of types, because the list was wrong the first time - it said
    # `float | Decimal | Fraction` and rejected `numpy.int64`, which this library documents support for
    # and which the runtime compares happily. `str`, `complex`, `date` and containers have no
    # `__float__`, so the mistakes worth catching stay caught
    _Number = SupportsFloat

    # Predicates read `Callable[[Any], object]`, or `[Any, Any]` where the runtime hands over a pair.
    # The verdict is `object` because the runtime reads it for truth: `bool` refused a `numpy.bool_`
    # verdict, the same mistake the numeric bound made once by naming types and rejecting `numpy.int64`.
    # The arity is the runtime's: `each` and its neighbours call with one argument, `zip_satisfies` and
    # `comparators` with two, and either raises when handed the other.

    class _MembershipAssertion(Protocol):
        """ "Is every one of my elements in there" asked the same way by three different types.

        Only `is_subset_of` lives here, and the reason `contains` does not is worth keeping: a string
        declares it as `str | Matcher[str]`, while a mapping and a byte string declare it untyped.
        Lifting the untyped form into a shared base looked like removing a duplicate and was really
        widening the string: `assert_that("abc").contains(123)` stopped being an error.  A capability
        protocol may only carry a declaration that every carrier means identically.
        """

        def is_subset_of(self, *supersets: object, allow_empty: bool = ...) -> Self: ...

    class _SizedAssertion(Protocol):
        """What every value with a length can be asked, declared once instead of in four protocols.

        Not on `_CoreAssertion`, because a number has no length and offering `is_empty()` on one would be
        the false promise this whole file exists to avoid.  Not generated either: a protocol that other
        protocols inherit is the language's own way of saying "these share a capability", and a checker
        understands it without anything being generated, recorded or kept in step.
        """

        def has_same_size_as(self, other: object) -> Self: ...
        def has_size_greater_than(self, size: int) -> Self: ...
        def has_size_less_than(self, size: int) -> Self: ...
        def has_size_between(self, low: int, high: int) -> Self: ...
        def is_empty(self) -> Self: ...
        def is_not_empty(self) -> Self: ...

