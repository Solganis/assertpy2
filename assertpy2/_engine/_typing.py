    class _ComplexAssertion(_ZeroAssertion, _CoreAssertion, Protocol):
        """Assertions available for ``complex`` values, which is far fewer than for a real number.

        Ordering is not defined for a complex number, and neither is parity, divisibility, NaN or
        infinity: the runtime refuses all thirteen of those with `TypeError: ordering is not defined for
        type <complex>` and its relatives.  It used to advertise them anyway, because `complex` shared
        the numeric protocol, so a checker suggested a method whose only outcome was a crash.
        """

        @property
        def value(self) -> complex: ...

    class _BoolAssertion(_RealNumberAssertion, _ZeroAssertion, _CoreAssertion, Protocol):
        """Assertions available for ``bool``, which is every numeric one except the integer-only three.

        `bool` is a subclass of `int`, so it used to resolve to the numeric protocol and be offered
        `is_even`, `is_odd` and `is_divisible_by`.  The runtime refuses exactly those three with
        `TypeError: val is not an integer, got bool`, and accepts the rest: `True > 0` is a real
        comparison.  The type now says the same thing.
        """

        @property
        def value(self) -> bool: ...

